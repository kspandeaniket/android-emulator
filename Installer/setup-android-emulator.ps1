Write-Host "Using: $javaExe"
Write-Host "       $javaVer"
$env:SKIP_JDK_VERSION_CHECK = '1'   # newer JDKs print "27", which old checks misread

# ----------------------------------------------------------------- 2. command-line tools
Write-Step '2/7  Android command-line tools'
$sdkmanager = Join-Path $SdkRoot 'cmdline-tools\latest\bin\sdkmanager.bat'
$avdmanager = Join-Path $SdkRoot 'cmdline-tools\latest\bin\avdmanager.bat'

if (Test-Path $sdkmanager) {
    Write-Host "Already present in $SdkRoot"
} else {
    New-Item -ItemType Directory -Force -Path $SdkRoot | Out-Null
    Write-Host 'Looking up the current command-line tools download...'
    $zipUrl = $null
    try {
        $resp = Invoke-WebRequest -UseBasicParsing 'https://dl.google.com/android/repository/repository2-3.xml'
        [xml]$repo = $resp.Content
        $pkgs = @($repo.GetElementsByTagName('remotePackage') | Where-Object { $_.path -eq 'cmdline-tools;latest' })
        $stable = @($pkgs | Where-Object { $_.channelRef.ref -eq 'channel-0' })
        if ($stable.Count -gt 0) { $pkgs = $stable }
        $best = $pkgs | Sort-Object { [int]$_.revision.major }, { [int]$_.revision.minor } -Descending | Select-Object -First 1
        $arc  = $best.archives.archive | Where-Object { $_.'host-os' -eq 'windows' } | Select-Object -First 1
        if ($arc) { $zipUrl = 'https://dl.google.com/android/repository/' + $arc.complete.url }
    } catch {
        Write-Warning "Could not read the repository manifest: $($_.Exception.Message)"
    }
    if (-not $zipUrl) {
        Write-Host 'Open https://developer.android.com/studio#command-line-tools-only,'
        Write-Host 'copy the Windows "Command line tools only" zip link and paste it here.'
        $zipUrl = (Read-Host 'Zip URL').Trim()
    }

    $tmp = Join-Path $env:TEMP ('android-cmdline-' + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Force -Path $tmp | Out-Null
    $zip = Join-Path $tmp 'cmdline-tools.zip'
    Write-Host "Downloading $zipUrl"
    Invoke-WebRequest -UseBasicParsing $zipUrl -OutFile $zip
    Expand-Archive -Path $zip -DestinationPath $tmp -Force

    $dest = Join-Path $SdkRoot 'cmdline-tools\latest'
    New-Item -ItemType Directory -Force -Path (Split-Path $dest) | Out-Null
    if (Test-Path $dest) { Remove-Item -Recurse -Force $dest }
    Move-Item -Path (Join-Path $tmp 'cmdline-tools') -Destination $dest
    Remove-Item -Recurse -Force $tmp
    if (-not (Test-Path $sdkmanager)) { throw "sdkmanager not found after extraction at $sdkmanager" }
    Write-Host 'Command-line tools installed.'
}

# ----------------------------------------------------------------- 3. environment
Write-Step '3/7  Environment variables'
[Environment]::SetEnvironmentVariable('ANDROID_HOME',     $SdkRoot, 'User')
[Environment]::SetEnvironmentVariable('ANDROID_SDK_ROOT', $SdkRoot, 'User')
$env:ANDROID_HOME     = $SdkRoot
$env:ANDROID_SDK_ROOT = $SdkRoot
Add-UserPath (Join-Path $SdkRoot 'cmdline-tools\latest\bin')
Add-UserPath (Join-Path $SdkRoot 'platform-tools')
Add-UserPath (Join-Path $SdkRoot 'emulator')
Write-Host "ANDROID_HOME = $SdkRoot"
Write-Host 'PATH updated (applies to NEW terminals).'

# ----------------------------------------------------------------- 4. licenses
Write-Step '4/7  Accepting SDK licenses'
Invoke-Native { 1..100 | ForEach-Object { 'y' } | & $sdkmanager "--sdk_root=$SdkRoot" --licenses | Out-Null }
Write-Host 'Done.'

# ----------------------------------------------------------------- 5. list + choose
Write-Step '5/7  Listing available packages (can take a minute)'
# Newer tools print names with slashes (system-images/android-37.2/...), older ones with ';'.
# The first run may also unpack the Android CLI, which can fail briefly; retry a few times.
$listText = ''
$bundles  = Join-Path $env:USERPROFILE '.android\cli\bundles'
for ($attempt = 1; $attempt -le 3; $attempt++) {
    if (Test-Path -LiteralPath $bundles) {
        Get-ChildItem -LiteralPath $bundles -Directory -Filter '*.extract' -ErrorAction SilentlyContinue |
            ForEach-Object { Remove-Item -LiteralPath $_.FullName -Recurse -Force -ErrorAction SilentlyContinue }
    }
    $out = Invoke-Native { & $sdkmanager "--sdk_root=$SdkRoot" --list 2>&1 | ForEach-Object { "$_" } }
    $listText = ($out | Out-String)
    if ($listText -match 'system-images[;/]') { break }
    if ($listText -match 'Access is denied') {
        Write-Warning "Attempt $attempt/3: the Android CLI could not unpack itself. Retrying in 5 s..."
        Start-Sleep -Seconds 5
    } else { break }
}
$listFile = Join-Path $env:TEMP 'sdkmanager-list.txt'
Set-Content -Path $listFile -Value $listText -Encoding UTF8
$slashNames = ($listText -match 'system-images/')

$arch = 'x86_64'
if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { $arch = 'arm64-v8a' }
Write-Host "CPU architecture -> using '$arch' images"

$all = foreach ($m in [regex]::Matches($listText, 'system-images[;/](android-[^;/\s|]+)[;/]([^;/\s|]+)[;/]([^;/\s|]+)')) {
    [pscustomobject]@{
        Api = $m.Groups[1].Value
        Tag = $m.Groups[2].Value
        Abi = $m.Groups[3].Value
        Id  = ('system-images;{0};{1};{2}' -f $m.Groups[1].Value, $m.Groups[2].Value, $m.Groups[3].Value)
    }
}
$all = @($all | Sort-Object Id -Unique | Where-Object { $_.Abi -eq $arch -and $_.Tag -match '^(default|google_apis)' })
if ($all.Count -eq 0) {
    Write-Host ''
    Write-Host 'First lines of what sdkmanager returned:' -ForegroundColor Yellow
    ($listText -split "[\r\n]+" | Where-Object { $_.Trim() } | Select-Object -First 20) | ForEach-Object { Write-Host "  $_" }
    throw "No system images found for $arch. Full output: $listFile"
}

$incPreview = Read-Host 'Include beta/preview releases? [y/N]'
if ($incPreview -notmatch '^[yY]') {
    $all = @($all | Where-Object { $_.Api -match '^android-\d+(\.\d+)?$' })
    if ($all.Count -eq 0) { throw 'No stable images found. Re-run and answer "y" to include previews.' }
}

# ---- system image
$apis = @($all | Group-Object Api | Sort-Object { Get-VersionKey $_.Name }, Name -Descending)
$apiLabels = foreach ($g in $apis) {
    $note = ''
    if ($g.Name -notmatch '^android-\d+(\.\d+)?$') { $note = '  [beta/preview]' }
    "{0}{1}" -f $g.Name, $note
}
$apiIdx = Read-Choice 'Android versions (newest first):' @($apiLabels) 1
$chosenApi = $apis[$apiIdx].Name

$variants = @($all | Where-Object { $_.Api -eq $chosenApi } | Sort-Object Tag)
$varLabels = foreach ($v in $variants) { '{0,-28} {1}' -f $v.Tag, (Get-TagDescription $v.Tag) }
$defVar = 1
for ($i = 0; $i -lt $variants.Count; $i++) { if ($variants[$i].Tag -eq 'google_apis') { $defVar = $i + 1; break } }
if ($defVar -eq 1) {
    for ($i = 0; $i -lt $variants.Count; $i++) { if ($variants[$i].Tag -eq 'google_apis_ps16k') { $defVar = $i + 1; break } }
}
$varIdx = Read-Choice "Image variants for $chosenApi ($arch):" @($varLabels) $defVar
$image = $variants[$varIdx]

# ---- platform
$platAll = @([regex]::Matches($listText, 'platforms[;/](android-[^;/\s|]+)') | ForEach-Object { $_.Groups[1].Value } | Sort-Object -Unique)
if ($incPreview -notmatch '^[yY]') { $platAll = @($platAll | Where-Object { $_ -match '^android-\d+(\.\d+)?$' }) }
$platAll = @($platAll | Sort-Object { Get-VersionKey $_ }, { $_ } -Descending)

$platformId = $null
if ($platAll.Count -gt 0) {
    $platLabels = @(foreach ($p in $platAll) {
        $note = ''
        if ($p -notmatch '^android-\d+(\.\d+)?$') { $note = '  [beta/preview/extension]' }
        if ($p -eq $chosenApi) { $note += '  <- matches your system image' }
        "{0}{1}" -f $p, $note
    })
    $platLabels += 'Skip (do not install a platform)'
    $defPlat = 1
    for ($i = 0; $i -lt $platAll.Count; $i++) { if ($platAll[$i] -eq $chosenApi) { $defPlat = $i + 1; break } }
    $platIdx = Read-Choice 'SDK Platform (newest first):' $platLabels $defPlat
    if ($platIdx -lt $platAll.Count) { $platformId = 'platforms;' + $platAll[$platIdx] }
}

$pkgs = @('emulator', 'platform-tools')
if ($platformId) { $pkgs += $platformId }
$pkgs += $image.Id

# ----------------------------------------------------------------- 6. install
Write-Step '6/7  Installing packages'
$installIds = @($pkgs | ForEach-Object { if ($slashNames) { $_ -replace ';', '/' } else { $_ } })
$installIds | ForEach-Object { Write-Host "  - $_" }
Invoke-Native { 1..100 | ForEach-Object { 'y' } | & $sdkmanager "--sdk_root=$SdkRoot" @installIds }
if ($LASTEXITCODE -ne 0) { throw "sdkmanager failed with exit code $LASTEXITCODE" }

# ----------------------------------------------------------------- 7. device + AVD
Write-Step '7/7  Device profile and virtual device'
if (-not $Device) {
    $out = Invoke-Native { & $avdmanager list device -c 2>&1 | ForEach-Object { "$_" } }
    $allDevs = @(($out | Out-String) -split "[\r\n]+" | ForEach-Object { $_.Trim() } |
        Where-Object { $_ -match '^[A-Za-z0-9_.\-]+$' } | Sort-Object -Unique)
    if ($allDevs.Count -eq 0) {
        Write-Warning 'avdmanager could not list device profiles; using a built-in list of common ones.'
        $builtin = @('pixel_9_pro_xl', 'pixel_9_pro', 'pixel_9', 'pixel_8_pro', 'pixel_8', 'pixel_7', 'pixel_6', 'pixel_tablet', 'pixel_fold', 'medium_phone', 'medium_tablet')
        $Device = $builtin[(Read-Choice 'Device profile:' $builtin 1)]
    } else {
        $cat = Read-Choice 'Which kind of device?' @(
            'Pixel phones (newest first)',
            'Tablets and foldables',
            'Wear OS / TV / Automotive / Desktop',
            'ALL device profiles'
        ) 1
        $devs = switch ($cat) {
            0 { @($allDevs | Where-Object { $_ -match '^pixel' -and $_ -notmatch 'tablet|fold|watch' }) }
            1 { @($allDevs | Where-Object { $_ -match 'tablet|fold|pixel_c|nexus_9|nexus_10|10\.1in|8in|7in' }) }
            2 { @($allDevs | Where-Object { $_ -match 'wear|tv|automotive|desktop|watch' }) }
            default { $allDevs }
        }
        if ($devs.Count -eq 0) { $devs = $allDevs }
        $devs = @($devs | Sort-Object { if ($_ -match '(\d+)') { [int]$Matches[1] } else { 0 } }, { $_ } -Descending)
        $Device = $devs[(Read-Choice 'Device profiles:' $devs 1)]
    }
}
Write-Host "Device: $Device"

if (-not $AvdName) {
    $suggest = ('{0}_{1}' -f $Device, ($chosenApi -replace '[^A-Za-z0-9]+', '_'))
    $AvdName = Read-Host "AVD name [Enter = $suggest]"
    if ([string]::IsNullOrWhiteSpace($AvdName)) { $AvdName = $suggest }
}
$AvdName = $AvdName -replace '[^A-Za-z0-9._-]', '_'

Invoke-Native { 'no' | & $avdmanager create avd -n $AvdName -k $image.Id -d $Device --force }
if ($LASTEXITCODE -ne 0) { throw "avdmanager failed with exit code $LASTEXITCODE (see output above)" }

# ----------------------------------------------------------------- finish
$emulator = Join-Path $SdkRoot 'emulator\emulator.exe'
Write-Host ''
Write-Host 'Hardware acceleration check:' -ForegroundColor Cyan
Invoke-Native { & $emulator -accel-check 2>&1 | ForEach-Object { "$_" } | Out-Host }
Write-Host 'If WHPX is reported as not installed: enable "Windows Hypervisor Platform" in' -ForegroundColor Yellow
Write-Host 'Windows Features (needs admin, then reboot) and enable virtualization in BIOS.' -ForegroundColor Yellow

Write-Step 'Optional: desktop shortcut with launcher window'
New-EmulatorShortcut -SdkRoot $SdkRoot -AvdName $AvdName

Write-Host ''
Write-Host "Done. AVD '$AvdName' created." -ForegroundColor Green
Write-Host 'Start it with the desktop shortcut, or from a NEW terminal:'
Write-Host "  emulator -avd $AvdName"
Write-Host '  add -no-window -no-audio for headless mode'
Write-Host 'For Expo: run "npx expo start" in your project and press "a".'
