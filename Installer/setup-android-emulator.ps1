# Runs a command block; stderr warnings from Java tools must not abort the script
function Invoke-Native([scriptblock]$Cmd) {
    $old = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try { & $Cmd } finally { $ErrorActionPreference = $old }
}

function Read-Choice {
    param([string]$Title, [string[]]$Items, [int]$Default = 1)
    Write-Host ''
    Write-Host $Title -ForegroundColor Cyan
    for ($i = 0; $i -lt $Items.Count; $i++) {
        $mark = ''
        if (($i + 1) -eq $Default) { $mark = '  (default)' }
        Write-Host ('  [{0}] {1}{2}' -f ($i + 1), $Items[$i], $mark)
    }
    while ($true) {
        $r = Read-Host ('Select 1-{0} [Enter = {1}]' -f $Items.Count, $Default)
        if ([string]::IsNullOrWhiteSpace($r)) { return ($Default - 1) }
        $n = 0
        if ([int]::TryParse($r, [ref]$n) -and $n -ge 1 -and $n -le $Items.Count) { return ($n - 1) }
        Write-Host 'Invalid choice, try again.' -ForegroundColor Yellow
    }
}

function Add-UserPath([string]$Dir) {
    $user = [Environment]::GetEnvironmentVariable('Path', 'User')
    if (-not $user) { $user = '' }
    $parts = @($user -split ';' | Where-Object { $_ })
    if ($parts -notcontains $Dir) {
        [Environment]::SetEnvironmentVariable('Path', (($parts + $Dir) -join ';'), 'User')
    }
    if ((@($env:Path -split ';')) -notcontains $Dir) { $env:Path = "$env:Path;$Dir" }
}

function Get-VersionKey([string]$Api) {
    $v = $Api -replace '^android-', ''
    if ($v -notmatch '^\d+(\.\d+)?$') { return [version]'0.0' }
    if ($v -notmatch '\.') { $v = "$v.0" }
    return [version]$v
}

function Get-TagDescription([string]$Tag) {
    $desc = switch -Regex ($Tag) {
        '^default'               { 'AOSP (no Google services)'; break }
        '^google_apis_playstore' { 'Google APIs + Play Store (no adb root)'; break }
        '^google_apis'           { 'Google APIs, no Play Store (good for testing, adb root works)'; break }
        default                  { $Tag }
    }
    if ($Tag -match 'ps16k') { $desc += '  [16 KB page size]' }
    return $desc
}

