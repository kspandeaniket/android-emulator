    if ($env:JAVA_HOME) {
        Write-Warning "JAVA_HOME points to a missing folder ($env:JAVA_HOME); ignoring it for this run."
        Remove-Item Env:JAVA_HOME
    }
    $cmd = Get-Command java.exe -ErrorAction SilentlyContinue
