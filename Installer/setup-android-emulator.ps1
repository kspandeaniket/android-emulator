function Get-ArgString {
    $a = @()
    if ($cmbAvd.Text) { $a += '-avd'; $a += $cmbAvd.Text }
    if ($chkNoAudio.Checked) { $a += '-no-audio' }
    if ($cmbGpu.Text)   { $a += '-gpu';      $a += $cmbGpu.Text }
    if ($cmbDelay.Text) { $a += '-netdelay'; $a += $cmbDelay.Text }
    if ($cmbSpeed.Text) { $a += '-netspeed'; $a += $cmbSpeed.Text }
    if ($chkNoAnim.Checked)  { $a += '-no-boot-anim' }
    if ($chkCold.Checked)    { $a += '-no-snapshot-load' }
    if ($chkNoSave.Checked)  { $a += '-no-snapshot-save' }
    if ($chkRO.Checked)      { $a += '-read-only' }
    if ($chkNoWin.Checked)   { $a += '-no-window' }
    if ($chkWipe.Checked)    { $a += '-wipe-data' }
    if ($chkMem.Checked)     { $a += '-memory'; $a += [string][int]$numMem.Value }
    if ($chkCores.Checked)   { $a += '-cores';  $a += [string][int]$numCores.Value }
    $line = $a -join ' '
    $x = $txtExtra.Text.Trim()
    if ($x) { $line = "$line $x" }
    return $line
}

