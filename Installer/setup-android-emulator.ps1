function New-LauncherLink {
    param([string]$LinkPath, [string]$LauncherPs1, [string]$SdkRoot, [string]$AvdName)
    $ws  = New-Object -ComObject WScript.Shell
    $lnk = $ws.CreateShortcut($LinkPath)
    $lnk.TargetPath = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
    $argLine = '-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "{0}" -SdkRoot "{1}"' -f $LauncherPs1, $SdkRoot
    if ($AvdName) { $argLine += (' -Avd "{0}"' -f $AvdName) }
    $lnk.Arguments        = $argLine
    $lnk.WorkingDirectory = $SdkRoot
    $lnk.IconLocation     = (Join-Path $SdkRoot 'emulator\emulator.exe') + ',0'
    $lnk.WindowStyle      = 7          # minimized, so no console flash
    $lnk.Description      = 'Android Emulator launcher'
    $lnk.Save()
}

function New-EmulatorShortcut {
    param([string]$SdkRoot, [string]$AvdName)

    $ans = Read-Host 'Create a desktop shortcut that opens the emulator launcher window? [Y/n]'
    if ($ans -match '^[nN]') { Write-Host 'Skipped.'; return }

    $dir = Join-Path $SdkRoot 'launcher'
    New-Item -ItemType Directory -Force -Path $dir | Out-Null
    $ps1 = Join-Path $dir 'emulator-launcher.ps1'
    Set-Content -Path $ps1 -Value $LauncherSource -Encoding UTF8   # BOM, so Windows PowerShell reads it correctly

    $desktop = [Environment]::GetFolderPath('Desktop')
    $link = Join-Path $desktop 'Android Emulator.lnk'
    New-LauncherLink -LinkPath $link -LauncherPs1 $ps1 -SdkRoot $SdkRoot -AvdName $AvdName
    Write-Host "Desktop shortcut created: $link" -ForegroundColor Green

    $ans = Read-Host 'Also add it to the Start Menu? [y/N]'
    if ($ans -match '^[yY]') {
        $programs = [Environment]::GetFolderPath('Programs')
        $link2 = Join-Path $programs 'Android Emulator.lnk'
        New-LauncherLink -LinkPath $link2 -LauncherPs1 $ps1 -SdkRoot $SdkRoot -AvdName $AvdName
        Write-Host "Start Menu shortcut created: $link2" -ForegroundColor Green
    }
    Write-Host "Launcher script: $ps1"
    Write-Host 'Your last-used options are remembered in %LOCALAPPDATA%\AndroidEmulatorLauncher\settings.json'
}

