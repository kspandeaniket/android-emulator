#Requires -Version 5.1
<#
.SYNOPSIS
  Sets up the standalone Android Emulator (no Android Studio) and creates an AVD.

.DESCRIPTION
  1. Checks Java (does not install it)
  2. Downloads the official Android command-line tools if missing
  3. Sets ANDROID_HOME and PATH (user level)
  4. Accepts SDK licenses
  5. Lists available system images and platforms; you choose
  6. Installs emulator, platform-tools, the platform and the system image
  7. Lets you choose a device profile and creates the AVD
  8. Optionally creates a desktop shortcut that opens a launcher window where you
     pick GPU mode, audio, network speed, boot options, etc. before the emulator starts

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\setup-android-emulator.ps1
  powershell -ExecutionPolicy Bypass -File .\setup-android-emulator.ps1 -SdkRoot D:\Android\sdk

.EXAMPLE
  # Already installed? Only (re)create the launcher + shortcut:
  powershell -ExecutionPolicy Bypass -File .\setup-android-emulator.ps1 -ShortcutOnly
#>
